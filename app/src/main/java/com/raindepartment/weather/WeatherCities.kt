    fun search(query: String): List<WeatherCity> {
        val normalizedQuery = normalizeSearchText(query)
        if (normalizedQuery.isEmpty()) return all
        return all.filter { city ->
            normalizeSearchText(city.labelAndAliases()).contains(normalizedQuery)
        }
    }

    private fun WeatherCity.labelAndAliases(): String = buildString {
        append(label)
        aliases.forEach {
            append(' ')
            append(it)
        }
    }

    private fun normalizeSearchText(value: String): String = Normalizer
        .normalize(value, Normalizer.Form.NFD)
        .replace(ACCENT_MARKS, "")
        .lowercase(Locale.ROOT)
        .replace(NON_WORD_CHARACTERS, " ")
        .trim()
        .replace(WHITESPACE, " ")

    private val ACCENT_MARKS = "\\p{M}+".toRegex()
    private val NON_WORD_CHARACTERS = "[^\\p{L}\\p{N}]+".toRegex()
    private val WHITESPACE = "\\s+".toRegex()
}
